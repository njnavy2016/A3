def build_prompt(template: str, **kwargs) -> str:
    """Prompt 模板变量填充"""
    # 安全地格式化
    try:
        return template.format(**kwargs)
    except KeyError as e:
        # 处理缺失变量
        import re
        missing = str(e).strip("'")
        template = template.replace("{" + missing + "}", f"[缺失: {missing}]")
        return template
